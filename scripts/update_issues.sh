#!/usr/bin/env bash
# Met à jour le texte (corps) des issues GitHub existantes avec les versions détaillées de .github/issues/<CODE>.md.
# Ne touche ni aux titres, ni aux assignés, ni aux labels. Peut être relancé sans risque.
set -euo pipefail
cd "$(dirname "$0")/.."
REPO=$(gh repo view --json nameWithOwner -q .nameWithOwner)
echo "Dépôt : $REPO"
LIST=$(gh issue list --state all --limit 300 --json number,title -q '.[] | "\(.number)\t\(.title)"')
upd() {
  local code="$1"
  local num
  num=$(printf '%s\n' "$LIST" | grep -F "[$code]" | head -1 | cut -f1 || true)
  if [ -z "$num" ]; then echo "introuvable : [$code] (lancer d'abord scripts/create_issues.sh)"; return; fi
  gh issue edit "$num" --body-file ".github/issues/$code.md" >/dev/null && echo "mise à jour : [$code] -> #$num" || echo "ÉCHEC : [$code] (#$num)"
}
upd "S1-01"
upd "S1-02"
